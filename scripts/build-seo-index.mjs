// Writes src/data/seoIndex.generated.js: the small part of the SEO data that the app shell
// (App, Nav, Footer) needs on every page — paths, titles, descriptions, language links and
// office details. The full page content stays in src/data/seoPages.js and is loaded only
// together with the page that shows it, so the first JavaScript file stays small.
// Runs before `vite` and `vite build` (see package.json); the output is committed as well.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { LANGUAGE_HOME_META, LOCATIONS, PRICE_PAGES, SEO_LANGUAGES, SEO_PAGES } from '../src/data/seoPages.js';
import { LANGUAGE_HUB_PATH } from '../src/data/languagePages.js';

const pick = (page) => {
  const entry = {
    path: page.path,
    lang: page.lang,
    kind: page.kind,
    group: page.group,
    serviceGroup: page.serviceGroup,
    serviceArea: page.serviceArea ? true : undefined,
    title: page.title,
    metaTitle: page.metaTitle,
    description: page.description,
    location: page.location,
  };
  return Object.fromEntries(Object.entries(entry).filter(([, value]) => value !== undefined));
};

const json = (value) => JSON.stringify(value);
const out = `// Generated by scripts/build-seo-index.mjs from src/data/seoPages.js. Do not edit by hand.
export const SEO_INDEX = ${json(SEO_PAGES.map(pick))};
export const PRICE_INDEX = ${json(PRICE_PAGES.map(pick))};
export const LOCATIONS = ${json(LOCATIONS)};
export const SEO_LANGUAGES = ${json(SEO_LANGUAGES)};
export const LANGUAGE_HOME_META = ${json(LANGUAGE_HOME_META)};
export const LANGUAGE_HUB_PATH = ${json(LANGUAGE_HUB_PATH)};
`;

const target = fileURLToPath(new URL('../src/data/seoIndex.generated.js', import.meta.url));
writeFileSync(target, out);
console.log(`SEO index: ${SEO_PAGES.length} pages, ${PRICE_PAGES.length} pricing pages, ${(out.length / 1024).toFixed(0)} KB`);
